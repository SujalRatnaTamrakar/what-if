"""One-page PDF request packet — §9.5 step 6 of the master plan.

US Letter, single page: header, title, place, exported timestamp, before/after
images side by side with labels, problem, change request, supporter count,
recipient, proposal id/link, and the AI-disclosure footer.
"""
from __future__ import annotations

import textwrap
import uuid
from datetime import datetime, timezone
from pathlib import Path

from django.conf import settings
from reportlab.lib.pagesizes import letter
from reportlab.lib.utils import ImageReader
from reportlab.pdfgen import canvas

PAGE_W, PAGE_H = letter
MARGIN = 54
CONTENT_W = PAGE_W - 2 * MARGIN


def _z(dt=None) -> str:
    return (dt or datetime.now(timezone.utc)).strftime("%Y-%m-%dT%H:%M:%SZ")


def _wrap(text: str, width: int) -> list[str]:
    lines: list[str] = []
    for para in (text or "").split("\n"):
        lines.extend(textwrap.wrap(para, width=width) or [""])
    return lines


def build_packet(proposal, support_count: int) -> tuple[Path, str]:
    """Render the packet PDF. Returns (full_path, rel_path)."""
    packets_dir = Path(settings.MEDIA_ROOT) / "packets"
    packets_dir.mkdir(parents=True, exist_ok=True)
    rel = f"packets/{uuid.uuid4().hex}.pdf"
    out = packets_dir / rel.split("/", 1)[1]

    # pageCompression=0 keeps text as literal strings in the PDF, which keeps
    # the artifact debuggable and text-searchable (images dominate the size).
    c = canvas.Canvas(str(out), pagesize=letter, pageCompression=0)
    y = PAGE_H - MARGIN

    def text(line: str, size: int = 11, bold: bool = False, gap: int = 15):
        nonlocal y
        c.setFont("Helvetica-Bold" if bold else "Helvetica", size)
        c.drawString(MARGIN, y, line[:110])
        y -= gap

    # Header
    text("WhatIf community request", size=16, bold=True, gap=22)
    text(proposal.title or "(untitled proposal)", size=13, bold=True, gap=18)
    text(f"Place: {proposal.place_label}", size=11, gap=15)
    text(f"Exported {_z()}  ·  Proposal {proposal.id}", size=9, gap=20)

    # Before / after images side by side
    img_w = (CONTENT_W - 18) / 2
    img_h = 200
    x_before, x_after = MARGIN, MARGIN + img_w + 18
    y_img = y - img_h
    for rel_path, x, label in (
        (proposal.source.file_path, x_before, "Before — submitted photo"),
        (getattr(proposal.concept, "file_path", None), x_after, "AI concept — illustration only"),
    ):
        if rel_path:
            try:
                reader = ImageReader(str(Path(settings.MEDIA_ROOT) / rel_path))
                iw, ih = reader.getSize()
                scale = min(img_w / iw, img_h / ih)
                dw, dh = iw * scale, ih * scale
                c.drawImage(reader, x + (img_w - dw) / 2, y_img + (img_h - dh), dw, dh,
                            preserveAspectRatio=True, anchor="c")
            except Exception:
                c.setFont("Helvetica-Oblique", 9)
                c.drawString(x, y_img + img_h / 2, "[image unavailable]")
        c.setFont("Helvetica", 9)
        c.drawString(x, y_img - 12, label[:60])
    y = y_img - 34

    # Body
    text("Problem", size=12, bold=True, gap=16)
    for line in _wrap(proposal.problem_text, 95):
        text(line, size=10, gap=13)
    y -= 6
    text("Change request", size=12, bold=True, gap=16)
    for line in _wrap(proposal.change_request, 95):
        text(line, size=10, gap=13)
    y -= 6
    text(f"Supporters as of export: {support_count}", size=11, gap=16)
    text(f"Recipient: {proposal.recipient_label}", size=11, gap=16)
    link = settings.APP_PUBLIC_WEB_URL
    text(f"Proposal ID: {proposal.id}" + (f"  ·  {link}" if link else ""), size=9, gap=30)

    # Footer — honesty rules (§1)
    c.setFont("Helvetica-Oblique", 9)
    footer = (
        f"{settings.AI_DISCLOSURE} Generated by WhatIf. "
        "Exporting this packet does not mean it has been sent to any organization."
    )
    for line in _wrap(footer, 100):
        c.drawString(MARGIN, y, line[:105])
        y -= 13

    c.showPage()
    c.save()
    return out, rel
